#!/usr/bin/env bash
# Build a "plus" grammar: an existing C++-based grammar (BASE grammar.js) extended with
# plus/plus_rules.js (and plus/extra_conflicts.json when present), generated with
# tree-sitter-cli 0.25 (ABI 15, the sandbox runtime) and compiled with node-gyp.
#   build_plus.sh NAME BASE_GRAMMAR_JS BASE_SCANNER_C
#   e.g. build_plus.sh cpp_plus /tank/projects/mcp-sandbox-server/node_modules/tree-sitter-cpp/grammar.js \
#                               /tank/projects/mcp-sandbox-server/node_modules/tree-sitter-cpp/src/scanner.c
# Output: grammars/tree-sitter-<name with dashes>/, requirable from the grammars folder.
set -euo pipefail
G=/tank/projects/mcp-sandbox-public/grammars
NAME=$1; BASE=$2; SCAN=$3
DASH=${NAME//_/-}
# each build goes to its own folder (a loaded .node is never overwritten under a running
# process); node_modules/tree-sitter-<name> is switched to it at the end
D=$G/builds/tree-sitter-$DASH-$(date +%Y%m%d-%H%M%S)
M=$G/tree-sitter-metal                      # binding skeleton source (already adapted once)
mkdir -p $D/bindings/node $D/src
cp $M/binding.gyp $D/binding.gyp
cp $M/bindings/node/binding.cc $M/bindings/node/index.js $M/bindings/node/index.d.ts $D/bindings/node/
# placeholders first, so a NAME that itself contains "metal" (metal_plus) is not renamed twice
sed -i "s/tree-sitter-metal/@DASH@/g; s/metal/@NAME@/g; s/Metal/@NAME@/g; s/@DASH@/tree-sitter-${DASH}/g; s/@NAME@/${NAME}/g" \
  $D/binding.gyp $D/bindings/node/*
cat > $D/package.json <<JSON
{
  "name": "tree-sitter-$DASH",
  "version": "0.1.0",
  "description": "$NAME: $(basename $(dirname $BASE)) grammar plus the sandbox's extra C++ rules",
  "license": "MIT",
  "main": "bindings/node",
  "types": "bindings/node",
  "dependencies": { "node-addon-api": "^8.5.0", "node-gyp-build": "^4.8.4" },
  "peerDependencies": { "tree-sitter": "^0.25.0" }
}
JSON
cat > $D/tree-sitter.json <<JSON
{
  "grammars": [{ "name": "$NAME", "camelcase": "$NAME", "title": "$NAME", "scope": "source.$NAME",
                 "path": ".", "file-types": [] }],
  "metadata": { "version": "0.1.0", "license": "MIT", "description": "$NAME grammar" }
}
JSON
cat > $D/grammar.js <<JS
// generated by plus/build_plus.sh — base: $BASE   rules: ${PLUS_ONLY:-all}
const BASE = require('$BASE');
const plusRules = require('$G/plus/plus_rules.js');
const rules = plusRules('${PLUS_ONLY:-}');
let extra = [];
try { extra = require('$G/plus/extra_conflicts.json'); } catch (e) {}
// only conflicts whose rules all exist in this build (a subset build lacks some plus rules)
const known = new Set([...Object.keys(BASE.grammar.rules), ...Object.keys(rules)]);
module.exports = grammar(BASE, {
  name: '$NAME',
  conflicts: (\$, original) => original.concat(
    extra.filter(names => names.every(n => known.has(n))).map(names => names.map(n => \$[n]))),
  rules,
});
JS
cd $D
NODE_PATH=$G/node_modules npx --yes tree-sitter-cli@0.25.10 generate --abi 15
sed -E "s/tree_sitter_[a-z_]+_external_scanner/tree_sitter_${NAME}_external_scanner/g" $SCAN > src/scanner.c
NODE_PATH=$G/node_modules npx --yes node-gyp rebuild > build.log 2>&1 || { tail -30 build.log; exit 1; }
ln -sfn $D $G/node_modules/tree-sitter-$DASH
echo "built $NAME: $(ls build/Release/*.node)"
